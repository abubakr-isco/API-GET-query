// Загружаем все посты сразу при открытии страницы
axios.get('https://jsonplaceholder.typicode.com/posts')
  .then(function (response) {
    const posts = response.data; // 100 постов
    const first10 = posts.slice(0, 10); // берём только первые 10
    const container = document.querySelector('.posts-list');
    let html = '';

    console.log(posts); // проверьте структуру

    first10.forEach(function (post) {
      const local = localPosts[post.id] || {};
      const title = local.title || post.title;
      const body = local.body || post.body;

      html += `
        <div class="post-card">
          <span class="post-id">#${post.id}</span>
          <h3>${title}</h3>
          <p>${body}</p>
        </div>
      `;
    });

    container.innerHTML = html;

    // Показываем, сколько постов выведено из общего числа
    document.querySelector('.info').innerText =
      `Показано ${first10.length} из ${posts.length}`;
  })
  .catch(function (error) {
    console.log('Ошибка:', error);
    document.querySelector('.posts-list').innerHTML =
      '<p class="error">Не удалось загрузить посты. Проверьте интернет.</p>';
  });